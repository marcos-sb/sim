import sys
import csv
import argparse
import matplotlib.pyplot as plt

def main():
    parser = argparse.ArgumentParser(description='Visualize simulation output CSV.')
    parser.add_argument('csv_file', help='Path to the CSV file generated by simulate.py')
    parser.add_argument('--output', '-o', help='Save plot to file instead of showing')
    args = parser.parse_args()

    generations = []
    trait_data = []  # list of lists, each inner list for a trait

    with open(args.csv_file, 'r') as f:
        reader = csv.DictReader(f)
        # Determine trait columns: all columns except 'generation'
        fieldnames = reader.fieldnames
        trait_cols = [col for col in fieldnames if col != 'generation']
        # Initialize data containers
        trait_data = [[] for _ in range(len(trait_cols))]
        for row in reader:
            generations.append(int(row['generation']))
            for i, col in enumerate(trait_cols):
                trait_data[i].append(float(row[col]))

    plt.figure(figsize=(10, 6))
    for i, data in enumerate(trait_data):
        label = trait_cols[i].replace('_avg', '').replace('trait', 'Trait ')
        plt.plot(generations, data, label=label)
    plt.xlabel('Generation')
    plt.ylabel('Average Trait Value')
    plt.title('Trait Evolution over Generations')
    plt.legend()
    plt.grid(True, linestyle='--', alpha=0.5)
    if args.output:
        plt.savefig(args.output, dpi=150)
        print(f'Plot saved to {args.output}')
    else:
        plt.show()

if __name__ == '__main__':
    main()