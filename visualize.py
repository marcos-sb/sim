import argparse
import csv

import matplotlib.pyplot as plt


def _pretty_label(col):
    if col == "average_trait":
        return "Trait"
    return (
        col.replace("_avg", "")
        .replace("trait", "Trait ")
        .replace("speed", "Speed")
        .replace("size", "Size")
    )


def main():
    parser = argparse.ArgumentParser(description="Visualize simulation output CSV.")
    parser.add_argument("csv_file", help="Path to the CSV file generated by simulate.py")
    parser.add_argument("--output", "-o", help="Save plot to file instead of showing")
    parser.add_argument(
        "--traits",
        default="",
        help='Comma-separated trait indices to plot (multi-trait only, e.g. "0,2"). Default: all traits.',
    )
    parser.add_argument(
        "--with-body",
        action="store_true",
        help="Also plot speed_avg / size_avg series when present.",
    )
    args = parser.parse_args()

    with open(args.csv_file, "r") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames or []
        rows = list(reader)

    if "generation" not in fieldnames:
        parser.error("CSV must contain a 'generation' column")
    generations = [int(r["generation"]) for r in rows]

    trait_cols = [c for c in fieldnames if c.startswith("trait") and c.endswith("_avg")]
    single_col = "average_trait" in fieldnames
    body_cols = [c for c in ("speed_avg", "size_avg") if c in fieldnames]

    if trait_cols:
        wanted = set(trait_cols)
        if args.traits.strip():
            try:
                idx = [int(p.strip()) for p in args.traits.split(",")]
            except ValueError:
                parser.error("--traits must be comma-separated integers")
            wanted = {f"trait{i}_avg" for i in idx}
            unknown = sorted(wanted - set(trait_cols))
            if unknown:
                parser.error(f"unknown trait column(s): {', '.join(unknown)}")
        plot_cols = [c for c in fieldnames if c in wanted]
    elif single_col:
        if args.traits.strip():
            parser.error("--traits only applies to multi-trait CSVs")
        plot_cols = ["average_trait"]
    else:
        parser.error("no plottable trait columns found")

    if args.with_body:
        plot_cols += [c for c in body_cols if c not in plot_cols]

    plt.figure(figsize=(10, 6))
    for col in plot_cols:
        plt.plot(generations, [float(r[col]) for r in rows], label=_pretty_label(col))
    plt.xlabel("Generation")
    plt.ylabel("Average Value")
    plt.title("Trait Evolution over Generations")
    plt.legend()
    plt.grid(True, linestyle="--", alpha=0.5)
    if args.output:
        plt.savefig(args.output, dpi=150)
        print(f"Plot saved to {args.output}")
    else:
        plt.show()


if __name__ == "__main__":
    main()
